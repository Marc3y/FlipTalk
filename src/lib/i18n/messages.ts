export const LANGS = ["de", "en"] as const;
export type Lang = (typeof LANGS)[number];
export const DEFAULT_LANG: Lang = "de";
export const LANG_COOKIE = "lang";

const messages: Record<Lang, Record<MessageKey, string>> = { de, en };

export type MessageParams = Record<string, string | number>;

export function isLang(value: unknown): value is Lang {
  return typeof value === "string" && (LANGS as readonly string[]).includes(value);
}

export function translate(lang: Lang, key: MessageKey, params?: MessageParams) {
  const text = messages[lang][key] ?? messages[DEFAULT_LANG][key] ?? key;
  return params ? text.replace(/\{(\w+)\}/g, (m, name) => (name in params ? String(params[name]) : m)) : text;
}

/** Fixed locale per language, so server and client format numbers identically (no hydration mismatch). */
export function formatNumber(lang: Lang, n: number) {
  return n.toLocaleString(lang === "de" ? "de-DE" : "en-US");
}

/** Reads the language from a raw Cookie header (API routes). */
export function langFromCookieHeader(header: string | null): Lang {
  const value = header?.match(/(?:^|;\s*)lang=([^;]+)/)?.[1];
  return isLang(value) ? value : DEFAULT_LANG;
}
